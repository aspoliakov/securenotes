package com.aspoliakov.securenotes.auth_providers

import android.app.Activity
import android.app.Application
import android.content.Intent
import android.os.Bundle
import androidx.activity.ComponentActivity
import androidx.activity.result.ActivityResult
import androidx.activity.result.ActivityResultLauncher
import androidx.activity.result.contract.ActivityResultContracts
import com.aspoliakov.securenotes.android.R
import com.aspoliakov.securenotes.feature_auth.presentation.auth_providers.GoogleSignInLauncher
import com.google.android.gms.auth.api.signin.GoogleSignIn
import com.google.android.gms.auth.api.signin.GoogleSignInOptions
import com.google.android.gms.auth.api.signin.GoogleSignInStatusCodes
import com.google.android.gms.common.api.ApiException
import java.lang.ref.WeakReference

/**
 * Project SecureNotes
 */
class AndroidGoogleSignInLauncher(
        private val application: Application,
) : GoogleSignInLauncher {

    companion object {
        private const val RESULT_KEY = "google_sign_in"
    }

    private var currentActivity: WeakReference<ComponentActivity>? = null
    private var pendingRequest: PendingRequest? = null
    private var registration: Registration? = null

    init {
        application.registerActivityLifecycleCallbacks(ActivityTracker())
    }

    override fun signIn(
            onIdTokenReceived: (idToken: String) -> Unit,
            onCancelled: () -> Unit,
            onError: () -> Unit,
    ) {
        val options = GoogleSignInOptions.Builder(GoogleSignInOptions.DEFAULT_SIGN_IN)
                // Generated by the google-services plugin from google-services.json
                .requestIdToken(application.getString(R.string.default_web_client_id))
                .requestEmail()
                .build()
        val client = GoogleSignIn.getClient(application, options)
        pendingRequest = PendingRequest(
                onIdTokenReceived = onIdTokenReceived,
                onCancelled = onCancelled,
                onError = onError,
        )
        // Always show the account picker instead of silently reusing the previous account
        client.signOut().addOnCompleteListener {
            val activity = currentActivity?.get()
            if (activity == null) {
                finishWithError()
                return@addOnCompleteListener
            }
            register(activity).launch(client.signInIntent)
        }
    }

    private fun register(activity: ComponentActivity): ActivityResultLauncher<Intent> {
        registration?.launcher?.unregister()
        val launcher = activity.activityResultRegistry.register(
                RESULT_KEY,
                ActivityResultContracts.StartActivityForResult(),
                ::onResult,
        )
        registration = Registration(activity = WeakReference(activity), launcher = launcher)
        return launcher
    }

    private fun onResult(result: ActivityResult) {
        registration?.launcher?.unregister()
        registration = null
        val request = pendingRequest ?: return
        pendingRequest = null
        try {
            val account = GoogleSignIn.getSignedInAccountFromIntent(result.data).getResult(ApiException::class.java)
            val idToken = account.idToken
            if (idToken != null) {
                request.onIdTokenReceived(idToken)
            } else {
                request.onError()
            }
        } catch (e: ApiException) {
            if (e.statusCode == GoogleSignInStatusCodes.SIGN_IN_CANCELLED) {
                request.onCancelled()
            } else {
                request.onError()
            }
        }
    }

    private fun finishWithError() {
        val request = pendingRequest ?: return
        pendingRequest = null
        request.onError()
    }

    private data class PendingRequest(
            val onIdTokenReceived: (idToken: String) -> Unit,
            val onCancelled: () -> Unit,
            val onError: () -> Unit,
    )

    private data class Registration(
            val activity: WeakReference<ComponentActivity>,
            val launcher: ActivityResultLauncher<Intent>,
    )

    private inner class ActivityTracker : Application.ActivityLifecycleCallbacks {

        override fun onActivityCreated(activity: Activity, savedInstanceState: Bundle?) {
            if (activity !is ComponentActivity) {
                return
            }
            currentActivity = WeakReference(activity)
            // The registry is already restored here, so the result of a sign-in launched
            // from the previous instance of the activity is delivered to this registration
            if (pendingRequest != null && registration != null) {
                register(activity)
            }
        }

        override fun onActivityDestroyed(activity: Activity) {
            if (currentActivity?.get() === activity) {
                currentActivity = null
            }
            val registered = registration
            if (registered != null && registered.activity.get() === activity && !activity.isChangingConfigurations) {
                // The activity is finishing for good: nobody is left to receive the result
                registered.launcher.unregister()
                registration = null
                finishWithError()
            }
        }

        override fun onActivityStarted(activity: Activity) {}

        override fun onActivityResumed(activity: Activity) {}

        override fun onActivityPaused(activity: Activity) {}

        override fun onActivityStopped(activity: Activity) {}

        override fun onActivitySaveInstanceState(activity: Activity, outState: Bundle) {}
    }
}
